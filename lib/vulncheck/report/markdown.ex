defmodule VulnCheck.Report.Markdown do
  @moduledoc """
  GitHub Flavored Markdown report (`--format markdown`) for pull request
  comments and audit wikis.

  Reachable and potentially reachable findings are expanded with their call
  chains; the evidence for unreachable advisories is folded into a
  `<details>` block.
  """

  @behaviour VulnCheck.Report.Formatter

  alias VulnCheck.Report.Formatter
  alias VulnCheck.Types.{Finding, ScanReport, Summary, Workspace}

  @impl true
  def render(%ScanReport{} = report, _config) do
    groups = Formatter.by_verdict(report.findings)

    [
      "## VulnCheck report" <> project_suffix(report.workspace),
      target(report),
      metrics(report.summary),
      section("Reachable", groups.reachable),
      section("Potentially reachable", groups.potentially_reachable),
      section("Retired releases", groups.retired),
      unreachable(groups.unreachable),
      suppressed(Enum.filter(report.findings, & &1.suppressed)),
      bullets("Policy violations", report.policy_violations),
      bullets("Warnings", report.warnings),
      "<sub>Generated by VulnCheck #{report.tool_version} in #{report.duration_ms} ms.</sub>"
    ]
    |> List.flatten()
    |> Enum.reject(&is_nil/1)
    |> Enum.join("\n\n")
    |> Kernel.<>("\n")
  end

  defp project_suffix(%Workspace{project_name: name}), do: " — `#{name}`"
  defp project_suffix(_workspace), do: ""

  defp target(%ScanReport{workspace: %Workspace{} = ws}) do
    runtime =
      [ws.elixir_version && "Elixir #{ws.elixir_version}", "OTP #{ws.otp_release}"]
      |> Enum.reject(&is_nil/1)
      |> Enum.join(" / ")

    prod = ws |> Workspace.prod_packages() |> length()
    non_prod = ws |> Workspace.non_prod_packages() |> length()

    "**Target:** #{ws.project_type} project, #{runtime}, env `#{ws.env}` · " <>
      "#{prod} prod packages (#{non_prod} dev/test excluded)"
  end

  defp target(_report), do: nil

  defp metrics(%Summary{} = s) do
    rows = [
      {"Reachable", s.reachable},
      {"Potentially reachable", s.potentially_reachable},
      {"Retired releases", s.retired},
      {"Unreachable", s.unreachable},
      {"Suppressed", s.suppressed},
      {"Expired suppressions", s.expired_suppressions},
      {"Noise reduction", "#{Summary.noise_reduction(s)}%"}
    ]

    table(["Metric", "Count"], [:left, :right], Enum.map(rows, fn {k, v} -> [k, to_string(v)] end))
  end

  defp section(_title, []), do: nil

  defp section(title, findings) do
    ["### #{title} (#{length(findings)})" | Enum.map(findings, &finding/1)]
  end

  defp finding(%Finding{} = f) do
    fix = Formatter.fix_text(f)

    facts =
      [
        {"Severity", Formatter.severity_text(f)},
        {"Fix", fix && code(fix)},
        {"Summary", inline(f.summary)},
        {"Target", f.target_mfa && code(Formatter.mfa(f.target_mfa))},
        {"Verdict", "`#{f.verdict}` — #{Formatter.reason_label(f.reason)}"},
        {"Detail", inline(f.reason_detail)}
      ]
      |> Enum.reject(fn {_k, v} -> v in [nil, ""] end)
      |> Enum.map_join("\n", fn {k, v} -> "- **#{k}:** #{v}" end)

    heading = "#### #{escape(Formatter.display_id(f))} — `#{f.package}` #{f.installed_version}"
    Enum.reject([heading, facts, trace_table(f)], &is_nil/1) |> Enum.join("\n\n")
  end

  defp trace_table(%Finding{trace: []}), do: nil

  defp trace_table(%Finding{trace: hops}) do
    rows =
      hops
      |> Enum.with_index(1)
      |> Enum.map(fn {hop, index} ->
        location = Formatter.location(hop)

        [
          to_string(index),
          cell_code(Formatter.mfa(hop.mfa)),
          (location && cell_code(location)) || ""
        ]
      end)

    table(["#", "Call", "Location"], [:right, :left, :left], rows)
  end

  defp unreachable([]), do: nil

  defp unreachable(findings) do
    rows =
      Enum.map(findings, fn f ->
        [
          escape(Formatter.display_id(f)),
          cell_code(f.package),
          f.installed_version,
          Formatter.severity_label(f.severity),
          cell_code(Atom.to_string(f.reason)),
          inline(f.reason_detail)
        ]
      end)

    """
    <details>
    <summary>Unreachable advisories (#{length(findings)})</summary>

    #{table(["Advisory", "Package", "Version", "Severity", "Reason", "Evidence"], List.duplicate(:left, 6), rows)}

    </details>\
    """
  end

  defp suppressed([]), do: nil

  defp suppressed(findings) do
    rows =
      Enum.map(findings, fn f ->
        [
          escape(Formatter.display_id(f)),
          code(f.package),
          inline(f.suppression_reason || ""),
          f.suppression_expires || ""
        ]
      end)

    [
      "### Suppressed (#{length(findings)})",
      table(["Advisory", "Package", "Reason", "Expires"], List.duplicate(:left, 4), rows)
    ]
  end

  defp bullets(_title, []), do: nil

  defp bullets(title, items),
    do: "### #{title}\n\n" <> Enum.map_join(items, "\n", &("- " <> inline(&1)))

  defp table(header, aligns, rows) do
    rule =
      Enum.map(aligns, fn
        :right -> "---:"
        :left -> "---"
      end)

    [header, rule | rows]
    |> Enum.map_join("\n", fn cells -> "| " <> Enum.join(cells, " | ") <> " |" end)
  end

  defp code(text), do: "`" <> String.replace(text, "`", "'") <> "`"

  defp cell_code(text), do: text |> code() |> String.replace("|", "\\|")

  defp inline(nil), do: ""
  defp inline(text), do: text |> String.split() |> Enum.join(" ") |> escape()

  defp escape(text) do
    text
    |> String.replace("|", "\\|")
    |> String.replace("<", "&lt;")
    |> String.replace(">", "&gt;")
  end
end
