defmodule VulnCheck.Types.CallSite do
  @moduledoc """
  A source location (`file:line`) attached to a function call.
  """

  @enforce_keys [:mfa]
  defstruct [:mfa, :file, :line]

  @type t :: %__MODULE__{
          mfa: VulnCheck.Types.MFA.t(),
          file: String.t() | nil,
          line: non_neg_integer() | nil
        }
end

defmodule VulnCheck.Types.CallEdge do
  @moduledoc """
  A directed edge of the call graph.

  `file` and `line` describe the call site inside the caller. `kind` tells how
  the edge was discovered:

    * `:static_call` — a direct local/remote call or function capture
    * `:macro_expanded` — a call generated by macro expansion
    * `:behaviour_callback` — a callback wired by an OTP or framework behaviour
    * `:supervisor_child` — a module started or referenced as a child/plug
    * `:dynamic_apply` — an `apply/3` site resolved to a concrete target
    * `:imports` — an over-approximated edge derived from the `:imports` table of
      a `.beam` without debug info
  """

  @enforce_keys [:from, :to, :kind]
  defstruct [:from, :to, :file, :line, :kind]

  @type kind ::
          :static_call
          | :macro_expanded
          | :behaviour_callback
          | :supervisor_child
          | :dynamic_apply
          | :imports

  @type t :: %__MODULE__{
          from: VulnCheck.Types.MFA.t(),
          to: VulnCheck.Types.MFA.t(),
          file: String.t() | nil,
          line: non_neg_integer() | nil,
          kind: kind()
        }
end

defmodule VulnCheck.Types.DynamicCall do
  @moduledoc """
  A dynamic dispatch site (`apply/2,3` or `mod.fun(...)` with a non-literal
  module or function) that could not be resolved statically.
  """

  @enforce_keys [:caller]
  defstruct [:caller, :known_module, :known_function, :arity, :file, :line]

  @type t :: %__MODULE__{
          caller: VulnCheck.Types.MFA.t(),
          known_module: String.t() | nil,
          known_function: String.t() | nil,
          arity: non_neg_integer() | nil,
          file: String.t() | nil,
          line: non_neg_integer() | nil
        }
end

defmodule VulnCheck.Types.Entrypoint do
  @moduledoc """
  A root of the reachability analysis (application callback, configured
  adapter, extra entrypoint, exported library function, ...).
  """

  @enforce_keys [:mfa, :kind]
  defstruct [:mfa, :kind, source: ""]

  @type kind ::
          :application_start
          | :library_export
          | :daemon
          | :adapter
          | :extra
          | :entrypoint

  @type t :: %__MODULE__{
          mfa: VulnCheck.Types.MFA.t(),
          kind: kind(),
          source: String.t()
        }
end

defmodule VulnCheck.Types.ModuleSummary do
  @moduledoc """
  Everything the analyzer needs to know about one compiled module.

  Summaries contain only strings, integers, lists, maps and atoms defined by
  VulnCheck itself, so they can be cached with `:erlang.term_to_binary/1` and
  decoded with `:erlang.binary_to_term(bin, [:safe])`.

  `module_refs` lists module names that appear as literals inside a function
  (children of supervisors, plugs passed as options, adapters, ...).
  `init_literals` keeps the literal arguments of selected framework calls
  (for example `Plug.Parsers.init/1`) in the string-based literal encoding of
  `VulnCheck.Beam.AbstractWalker`.
  """

  @enforce_keys [:module]
  defstruct [
    :module,
    :beam_path,
    :source_file,
    :sha256,
    :package,
    has_debug_info: true,
    functions: [],
    exports: [],
    behaviours: [],
    attributes: %{},
    edges: [],
    dynamic_dispatches: [],
    module_refs: [],
    mfa_refs: [],
    init_literals: [],
    imports: []
  ]

  @type literal ::
          {:atom, String.t()}
          | {:tuple, [literal()]}
          | [literal()]
          | binary()
          | number()
          | :dynamic

  @type t :: %__MODULE__{
          module: String.t(),
          beam_path: String.t() | nil,
          source_file: String.t() | nil,
          sha256: String.t() | nil,
          package: String.t() | nil,
          has_debug_info: boolean(),
          functions: [{String.t(), non_neg_integer()}],
          exports: [{String.t(), non_neg_integer()}],
          behaviours: [String.t()],
          attributes: %{String.t() => term()},
          edges: [VulnCheck.Types.CallEdge.t()],
          dynamic_dispatches: [VulnCheck.Types.DynamicCall.t()],
          module_refs: [
            {VulnCheck.Types.MFA.t(), String.t(), String.t() | nil, non_neg_integer() | nil}
          ],
          mfa_refs: [VulnCheck.Types.CallEdge.t()],
          init_literals: [
            {VulnCheck.Types.MFA.t(), VulnCheck.Types.MFA.t(), [literal()], String.t() | nil,
             non_neg_integer() | nil}
          ],
          imports: [{String.t(), String.t(), non_neg_integer()}]
        }
end

defmodule VulnCheck.Types.EntrypointModel do
  @moduledoc """
  The BEAM-specific execution model synthesized from `.app` files,
  supervision trees, behaviours, framework macros and runtime configuration.
  """

  defstruct roots: [],
            synthetic_edges: [],
            started_otp_apps: [],
            active_daemon_packages: [],
            configured_adapters: %{},
            inactive_adapter_packages: %{},
            resolved_dynamic_modules: %{},
            active_plug_parsers: [],
            boot_tree_known: true,
            notes: []

  @type t :: %__MODULE__{
          roots: [VulnCheck.Types.Entrypoint.t()],
          synthetic_edges: [VulnCheck.Types.CallEdge.t()],
          started_otp_apps: [String.t()],
          active_daemon_packages: [String.t()],
          configured_adapters: %{atom() => [String.t()]},
          inactive_adapter_packages: %{String.t() => String.t()},
          resolved_dynamic_modules: %{String.t() => [String.t()]},
          active_plug_parsers: [String.t()] | :all,
          boot_tree_known: boolean(),
          notes: [String.t()]
        }
end
